import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { afterEach, beforeEach, describe, expect, it } from 'vitest';
import { cleanupTempDirs, git, tempDir } from '../helpers/git-fixture.js';
import { run } from '../helpers/run.js';

const lines = (n: number, text = 'line') => Array.from({ length: n }, (_, i) => `${text} ${i}`).join('\n') + '\n';

function write(root: string, file: string, content: string) {
  mkdirSync(dirname(join(root, file)), { recursive: true });
  writeFileSync(join(root, file), content);
}

/** Repo whose HEAD commit adds one reviewable file and one file of every kind diff.sh must skip. */
function repoWithMixedChange(): string {
  const dir = tempDir();
  git(dir, 'init', '-q', '-b', 'main');
  write(dir, 'README.md', 'base\n');
  git(dir, 'add', '.');
  git(dir, 'commit', '-q', '-m', 'base');
  git(dir, 'tag', 'base');

  write(dir, 'src/a.js', lines(5, 'code'));
  write(dir, 'package-lock.json', lines(50));
  write(dir, 'web/pnpm-lock.yaml', lines(50));
  write(dir, 'dist/bundle.js', lines(10));
  write(dir, 'src/app.min.js', lines(3));
  write(dir, 'src/__snapshots__/a.test.js.snap', lines(3));
  write(dir, 'src/gen.ts', '// Code generated by protoc. DO NOT EDIT.\n' + lines(3));
  write(dir, 'src/schema.ts', '/* @generated */\n' + lines(3));
  write(dir, 'src/attr.js', lines(3));
  write(dir, '.gitattributes', 'src/attr.js linguist-generated=true\n');
  write(dir, 'src/ignored/x.js', lines(3));
  write(dir, 'data/huge.json', lines(1200));
  git(dir, 'add', '.');
  git(dir, 'commit', '-q', '-m', 'change');
  return dir;
}

let dir: string;
beforeEach(() => {
  dir = repoWithMixedChange();
});
afterEach(cleanupTempDirs);

const field = (stdout: string, name: string) =>
  stdout.split('\n').filter((l) => l.startsWith(`${name}: `)).map((l) => l.slice(name.length + 2));

describe('diff.sh', () => {
  it('keeps reviewable files and writes the filtered diff to a file', () => {
    const r = run('diff.sh', ['base', 'src/ignored/*'], { cwd: dir });
    expect(r.code).toBe(0);
    const diff = readFileSync(field(r.stdout, 'diff')[0], 'utf8');
    expect(diff).toContain('+++ b/src/a.js');
    expect(diff).toContain('+++ b/.gitattributes');
    for (const skipped of ['package-lock.json', 'dist/bundle.js', 'data/huge.json', 'src/gen.ts']) {
      expect(diff).not.toContain(`b/${skipped}`);
    }
  });

  it('reports every skipped file with its reason', () => {
    const skipped = field(run('diff.sh', ['base', 'src/ignored/*'], { cwd: dir }).stdout, 'skipped').sort();
    expect(skipped).toEqual([
      'data/huge.json (too large: 1200 changed lines)',
      'dist/bundle.js (build output)',
      'package-lock.json (lockfile)',
      'src/__snapshots__/a.test.js.snap (snapshot)',
      'src/app.min.js (minified)',
      'src/attr.js (generated)',
      'src/gen.ts (generated)',
      'src/ignored/x.js (ignored by REVIEW.md)',
      'src/schema.ts (generated)',
      'web/pnpm-lock.yaml (lockfile)',
    ]);
  });

  it('counts files and changed lines of the kept part only', () => {
    const out = run('diff.sh', ['base', 'src/ignored/*'], { cwd: dir }).stdout;
    expect(field(out, 'files')).toEqual(['2']);
    expect(field(out, 'changed')).toEqual(['6']);
  });

  it('keeps the diff file out of the working tree', () => {
    run('diff.sh', ['base'], { cwd: dir });
    expect(git(dir, 'status', '--porcelain')).toBe('');
  });

  it('fails on an unknown base ref', () => {
    expect(run('diff.sh', ['no-such-ref'], { cwd: dir }).code).toBe(1);
  });
});
